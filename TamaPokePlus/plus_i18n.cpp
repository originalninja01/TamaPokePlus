const char *PT(PStrId id) {
  if (id >= P_COUNT) return "";
  switch (gLang) {
    case LANG_ES: return PSTR_ES[id];
    case LANG_FR: return PSTR_FR[id];
    case LANG_DE: return PSTR_DE[id];
    case LANG_IT: return PSTR_IT[id];
    case LANG_PT: return PSTR_PT[id];
    default: return PSTR_EN[id];
  }
}
